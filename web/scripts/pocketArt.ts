// Generates the Pocket Player's own art as C headers (committed): the Sandbox splash (the last full frame of the Sandbox sting,
// games/kit/sandlogo.ts, halved to 160x100 in 565 color) and the 16x16 category icons (drawn here in code, one shared 16-color palette).
//   cd web && npx vite-node scripts/pocketArt.ts [--preview <dir>]
// Writes hardware/pocket-player/src/splash_data.h and icons_data.h; --preview also writes splash.ppm and icons.ppm (4x, on the tile color).
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { applyFliFrame, newFliCanvas, parseFli } from '@lewismoten/gamemaker-sandbox-engine/formats/fli';

const out = '../hardware/pocket-player/src/';
const preview = process.argv.includes('--preview') ? process.argv[process.argv.indexOf('--preview') + 1] : '';
const rgb565 = (r: number, g: number, b: number) => ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3);
const hex = (v: number) => '0x' + v.toString(16).padStart(4, '0');

// ---- the splash: frame 40 of the sting has the whole logo lit with the star glints, before the fade starts ----
const disk = readdirSync('../games')
  .map((g) => `../games/${g}/disk/SANDLOGO.FLI`)
  .find((p) => existsSync(p));
if (!disk) throw new Error('no built game has SANDLOGO.FLI; run npm run build:games');
const anim = parseFli(new Uint8Array(readFileSync(disk)));
const canvas = newFliCanvas(anim);
for (let f = 0; f <= 40; f++) applyFliFrame(anim, f, canvas);
const v8 = (c: number) => ((c & 63) << 2) | ((c & 63) >> 4);
const px = (x: number, y: number): number[] => {
  const i = canvas.pixels[y * 320 + x] * 3;
  return [v8(canvas.palette[i]), v8(canvas.palette[i + 1]), v8(canvas.palette[i + 2])];
};
const splash: number[] = [];
for (let y = 0; y < 100; y++)
  for (let x = 0; x < 160; x++) {
    const sum = [0, 0, 0];
    for (const [dx, dy] of [
      [0, 0],
      [1, 0],
      [0, 1],
      [1, 1],
    ])
      px(x * 2 + dx, y * 2 + dy).forEach((v, k) => (sum[k] += v));
    splash.push(rgb565(sum[0] >> 2, sum[1] >> 2, sum[2] >> 2));
  }
const rows = (a: number[], n: number) =>
  Array.from(
    { length: a.length / n },
    (_, r) =>
      '  ' +
      a
        .slice(r * n, r * n + n)
        .map(hex)
        .join(',') +
      ',',
  ).join('\n');
writeFileSync(
  out + 'splash_data.h',
  `// Generated by web/scripts/pocketArt.ts: the Sandbox sting's last full frame (games/kit/sandlogo.ts), 160x100, RGB565 (host byte order). Do not edit.\n#pragma once\n#include <stdint.h>\nnamespace pk {\nconstexpr int SPLASH_W = 160, SPLASH_H = 100;\nstatic const uint16_t SPLASH[SPLASH_W * SPLASH_H] = {\n${rows(splash, 16)}\n};\n}  // namespace pk\n`,
);

