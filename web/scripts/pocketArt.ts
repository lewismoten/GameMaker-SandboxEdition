type Grid = string[][];
const blank = (): Grid => Array.from({ length: 16 }, () => Array<string>(16).fill('.'));
const set = (g: Grid, x: number, y: number, c: string) => {
  if (x >= 0 && x < 16 && y >= 0 && y < 16) g[Math.round(y)][Math.round(x)] = c;
};
const rect = (g: Grid, x: number, y: number, w: number, h: number, c: string) => {
  for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) set(g, x + i, y + j, c);
};
const disc = (g: Grid, cx: number, cy: number, r: number, c: string, inner = 0) => {
  for (let y = 0; y < 16; y++)
    for (let x = 0; x < 16; x++) {
      const d = Math.hypot(x - cx, y - cy);
      if (d <= r && d >= inner) set(g, x, y, c);
    }
};
const line = (g: Grid, x0: number, y0: number, x1: number, y1: number, c: string, thick = 1) => {
  const n = Math.max(Math.abs(x1 - x0), Math.abs(y1 - y0)) * 2;
  for (let i = 0; i <= n; i++) rect(g, Math.round(x0 + ((x1 - x0) * i) / n), Math.round(y0 + ((y1 - y0) * i) / n), thick, thick, c);
};
const art = (rowsText: string[]): Grid => rowsText.map((r) => r.padEnd(16, '.').split(''));

