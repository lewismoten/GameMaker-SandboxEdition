// Writes public/tour/voice/README.md for scripts/narrate.ts: the clips listed by chapter (file,
// words, where the tour uses it, seconds), for reviewing them. Generated; never edited by hand.
import { clipPath, type Line, type VoiceIndex } from './lineIndex';

/** Table cells: no pipes or line breaks. */
const cell = (text: string): string => text.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

/** The README for `lines` (in the tour's order), from what `index` recorded. */
export function voiceReadme(lines: Line[], index: VoiceIndex): string {
  const out = [
    '# Tour voice clips',
    '',
    '<!-- Generated by web/scripts/narrate.ts; never edit by hand. -->',
    '',
    "Each clip is one line of the guided tour, spoken in Lewis Moten's own voice, cloned (with his consent) by",
    '[Pocket TTS](https://huggingface.co/kyutai/pocket-tts) (Kyutai, CC BY 4.0) running locally. `index.json` has the',
    'same list for the tour to read.',
    '',
    'From `web/`: `npm run voice` records the lines that are new or whose words changed, and rewrites this file and',
    '`index.json`; `npm run voice -- --only <id>` records one clip again (each take differs); `npm run voice:all`',
    'records every clip again.',
  ];
  const chapters = [...new Set(lines.map((l) => l.chapter))];
  for (const chapter of chapters) {
    out.push('', `## ${chapter}`, '', '| Clip | Says | Where | Seconds |', '| --- | --- | --- | ---: |');
    for (const l of lines.filter((x) => x.chapter === chapter)) {
      const e = index[l.id];
      const file = clipPath(l).slice(chapter.length + 1);
      out.push(
        `| ${e ? `[${file}](${clipPath(l)})` : `${file} (not recorded)`} | ${cell(l.text)} | ${cell(l.where ?? '')} | ${e ? e.seconds.toFixed(2) : ''} |`,
      );
    }
  }
  return out.join('\n') + '\n';
}
