// Generates the service worker used both by the Game-Maker: Sandbox Edition site and by exported
// game web apps: precaches the listed files at install (the site lists only its app
// shell; an exported game lists everything), then serves same-origin GETs cache-first,
// adding anything else that is fetched (e.g. the editors, sample games) so it keeps
// working offline. A page can also post { cacheUrls: [...] } to cache what it loaded
// before the worker took control (see src/offline.ts).

export function serviceWorkerSource(version: string, precache: string[], fallback = './index.html'): string {
  return `// Generated by Game-Maker: Sandbox Edition. Cache version: ${version}
const CACHE = ${JSON.stringify(`gm-${version}`)};
const PRECACHE = ${JSON.stringify(precache.map((f) => `./${f.replace(/^\.?\//, '')}`))};
const FALLBACK = ${JSON.stringify(fallback)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('gm-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('message', (event) => {
  const urls = event.data && event.data.cacheUrls;
  if (!Array.isArray(urls)) return;
  event.waitUntil(caches.open(CACHE).then((cache) => Promise.all(urls.map(async (u) => {
    if (typeof u !== 'string' || new URL(u, self.location.href).origin !== self.location.origin) return;
    if (await cache.match(u, { ignoreSearch: true })) return;
    const res = await fetch(u).catch(() => undefined);
    if (res && res.ok && res.type === 'basic') await cache.put(u, res);
  }))));
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(req, { ignoreSearch: true });
    if (hit) return hit;
    try {
      const res = await fetch(req);
      if (res.ok && res.type === 'basic') cache.put(req, res.clone());
      return res;
    } catch (err) {
      if (req.mode === 'navigate') {
        const page = await cache.match(FALLBACK);
        if (page) return page;
      }
      throw err;
    }
  })());
});
`;
}

/** Short stable hash for cache versions. */
export function hashText(text: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return (h >>> 0).toString(36);
}
