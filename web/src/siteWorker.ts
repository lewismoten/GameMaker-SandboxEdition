// The Game-Maker: Sandbox Edition site's service worker (sw.js, written at build time by
// vite.config.ts; exported game web apps have their own, export/serviceWorker.ts).
//
// One cache, kept from one deploy to the next. A deploy changes few files, so nothing is
// thrown away just because the site was rebuilt:
// - assets/ (the code and styles) have the content's hash in their names: kept until a
//   build no longer has them.
// - everything else (the pages, the catalogs, a game's files, the desk's pictures) belongs
//   to a group (groupOf) whose content hash the build lists; when a new worker takes over,
//   the files of groups whose hash changed are dropped (fetched afresh when next used) and
//   the rest stays, offline included.
// A new worker downloads only the app shell files that changed, then waits: the page offers
// "Reload" (src/offline.ts) rather than swapping the site under a game being played. Until
// then the old version is served, whole.

/** Files with a content hash in their names. */
export const isHashed = (path: string): boolean => path.startsWith('assets/');

/**
 * The group a site file is versioned with: a game's folder (games/<kind>/<id>/), a folder of
 * pictures or text (desk/, bbs/, gm/…), or the file itself (the pages, the catalogs). Undefined
 * for hashed files, which never change.
 */
export function groupOf(path: string): string | undefined {
  if (isHashed(path)) return undefined;
  const parts = path.split('/');
  if (parts[0] === 'games' && parts.length >= 4) return `${parts.slice(0, 3).join('/')}/`;
  if (parts.length === 1 || parts[0] === 'games') return path;
  return `${parts[0]}/`;
}

interface SiteWorkerOptions {
  /** Changes whenever anything in the build does (the worker's file must change for browsers to update). */
  version: string;
  /** Installed up front: the pages and what they load before showing anything, the icons and manifest. */
  precache: string[];
  /** Content hash of each group in this build, by groupKey (the worker names no file or folder: a secret game's folder stays unnamed). */
  groups: Record<string, string>;
  /** Every hashed file in this build. */
  assets: string[];
}

export function siteWorkerSource(o: SiteWorkerOptions): string {
  const rel = (f: string) => (f === './' ? '' : f.replace(/^\.?\//, ''));
  return `// Generated by Game-Maker: Sandbox Edition (src/siteWorker.ts). Version: ${o.version}
const VERSION = ${JSON.stringify(o.version)};
const CACHE = 'gm-site';
const STAGE = 'gm-stage-' + VERSION;
const META = './__gm-version.json';
const PRECACHE = ${JSON.stringify(o.precache.map(rel))};
const GROUPS = ${JSON.stringify(o.groups)};
const ASSETS = new Set(${JSON.stringify(o.assets)});
const SCOPE = new URL('./', self.location.href).href;

${WORKER_GROUP_OF}

/** Path in the site, e.g. games/catalog.json ('' for the home page); undefined if outside it. */
function sitePath(url) {
  const u = new URL(url, SCOPE);
  if (!u.href.startsWith(SCOPE)) return undefined;
  return decodeURIComponent(u.pathname.slice(new URL(SCOPE).pathname.length));
}

/** The key of a file's group in GROUPS (the home page is served as its index.html). */
const groupFor = (path) => {
  const g = groupOf(path === '' ? 'index.html' : path);
  return g === undefined ? undefined : groupKey(g);
};

/** What the cache holds: { groups, assets } of the version that last took over. */
async function cachedVersion(cache) {
  const res = await cache.match(META);
  const v = res ? await res.json().catch(() => undefined) : undefined;
  return { groups: (v && v.groups) || {}, assets: (v && v.assets) || [] };
}

/** Still good in this version: a hashed file this build has, or one of a group whose content did not change. */
function unchanged(path, before) {
  if (isHashed(path)) return ASSETS.has(path);
  const g = groupFor(path);
  return g !== undefined && before.groups[g] !== undefined && before.groups[g] === GROUPS[g];
}

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    const before = await cachedVersion(cache);
    const stage = await caches.open(STAGE);
    await Promise.all(PRECACHE.map(async (path) => {
      const url = SCOPE + path;
      if (unchanged(path, before) && (await cache.match(url))) return; // kept from the last version
      const res = await fetch(new Request(url, { cache: 'no-cache' }));
      if (!res.ok) throw new Error('precache ' + path + ': ' + res.status);
      await stage.put(url, res);
    }));
    // the first visit has no older version to keep running: start serving at once
    if (!self.registration.active) await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    const before = await cachedVersion(cache);
    // drop what changed, keep the rest; and the code of the version before, for a while, for
    // a page still open on it that has yet to load a part
    const previous = new Set(before.assets);
    for (const req of await cache.keys()) {
      const path = sitePath(req.url);
      if (req.url === new URL(META, SCOPE).href) continue;
      if (path === undefined || !(unchanged(path, before) || (isHashed(path) && previous.has(path)))) await cache.delete(req);
    }
    // the shell files the install fetched
    if (await caches.has(STAGE)) {
      const stage = await caches.open(STAGE);
      for (const req of await stage.keys()) await cache.put(req, await stage.match(req));
    }
    await cache.put(META, new Response(JSON.stringify({ version: VERSION, groups: GROUPS, assets: [...ASSETS] }), { headers: { 'content-type': 'application/json' } }));
    // other versions' staging, and the caches of the workers before this one (gm-<version>)
    for (const k of await caches.keys()) if (k !== CACHE && /^gm-/.test(k)) await caches.delete(k);
    await self.clients.claim();
  })());
});

self.addEventListener('message', (event) => {
  const data = event.data || {};
  if (data.type === 'skip-waiting') return void self.skipWaiting();
  const urls = data.cacheUrls;
  if (!Array.isArray(urls)) return;
  // files the page loaded before this worker was running
  event.waitUntil(caches.open(CACHE).then((cache) => Promise.all(urls.map(async (u) => {
    if (typeof u !== 'string' || sitePath(u) === undefined) return;
    if (await cache.match(u, { ignoreSearch: true })) return;
    const res = await fetch(u).catch(() => undefined);
    if (res && res.ok && res.type === 'basic') await cache.put(u, res);
  }))));
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const path = sitePath(req.url);
  if (path === undefined || path === 'sw.js') return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(req, { ignoreSearch: true, ignoreVary: true }); // a host's Vary: Origin would miss a module script's request
    if (hit) return hit;
    try {
      const res = await fetch(req);
      if (res.ok && res.type === 'basic' && !req.headers.has('range')) cache.put(req, res.clone()).catch(() => undefined);
      return res;
    } catch (err) {
      if (req.mode === 'navigate') {
        // offline, and a page never opened: the home page
        const page = (await cache.match(SCOPE)) || (await cache.match(SCOPE + 'index.html'));
        if (page) return page;
      }
      throw err;
    }
  })());
});
`;
}

/** A group's key in the worker's list: a short hash of its name. */
export function groupKey(group: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < group.length; i++) {
    h ^= group.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return (h >>> 0).toString(36);
}

