#!/usr/bin/env python3
"""Turns art/hand-left.svg into src/handshape.h: the Pocket Player's "How to hold it" hand as polygons.

Art: made by Lewis Moten with ChatGPT's image generation (OpenAI); converted to firmware shapes by Claude Sonnet 5.5.
Stdlib only. Reads absolute M/L/H/V/Q/C/Z path data, applies the <g> transform (translate + scale), flattens the curves to
polylines (adaptive: a curve splits until its control points are within FLAT canvas units of the chord), and writes per path
its role, whether it is stroked and the points (whole units of the 1024 square), in draw order.
Run:  python3 hardware/pocket-player/tools/svgHand.py     (rewrites src/handshape.h)
"""
import re, os

HERE = os.path.dirname(os.path.abspath(__file__))
SVG = os.path.join(HERE, '..', 'art', 'hand-left.svg')
OUT = os.path.join(HERE, '..', 'src', 'handshape.h')
FLAT = 0.6
ROLES = {'#0789E6': 'cuff', '#FFC89D': 'skin', '#E99B6B': 'skinShade', '#F9BEA5': 'nail', '#FFDDC5': 'highlight', 'none': 'crease'}
NAMES = {'cuff': 'CUFF', 'skin': 'SKIN', 'skinShade': 'SKIN_SHADE', 'nail': 'NAIL', 'highlight': 'HIGHLIGHT', 'crease': 'CREASE'}


def flatten(ctrl_pts, p0, out):
    def mid(a, b): return ((a[0] + b[0]) / 2, (a[1] + b[1]) / 2)

    def sub(ctrl, depth):
        a, z = ctrl[0], ctrl[-1]
        dx, dy = z[0] - a[0], z[1] - a[1]
        length = (dx * dx + dy * dy) ** 0.5 or 1e-9
        dev = max(abs((c[0] - a[0]) * dy - (c[1] - a[1]) * dx) / length for c in ctrl[1:-1])
        if dev <= FLAT or depth > 8:
            out.append(z)
            return
        rows = [ctrl]
        while len(rows[-1]) > 1:
            r = rows[-1]
            rows.append([mid(r[i], r[i + 1]) for i in range(len(r) - 1)])
        sub([r[0] for r in rows], depth + 1)
        sub([r[-1] for r in reversed(rows)], depth + 1)

    sub([p0] + ctrl_pts, 0)


def parse_d(d):
    toks = re.findall(r'[MLHVQCZ]|-?\d*\.?\d+', d)
    subs, cur, i, cmd, pos = [], None, 0, None, (0.0, 0.0)

    def num():
        nonlocal i
        v = float(toks[i]); i += 1
        return v

    while i < len(toks):
        if toks[i] in NAMES.keys() or toks[i] in ('M', 'L', 'H', 'V', 'Q', 'C', 'Z'):
            cmd = toks[i]; i += 1
            if cmd == 'Z':
                if cur: subs.append(cur); cur = None
                continue
        if cmd == 'M':
            if cur: subs.append(cur)
            pos = (num(), num()); cur = [pos]; cmd = 'L'
        elif cmd == 'L': pos = (num(), num()); cur.append(pos)
        elif cmd == 'H': pos = (num(), pos[1]); cur.append(pos)
        elif cmd == 'V': pos = (pos[0], num()); cur.append(pos)
        elif cmd == 'Q':
            c = (num(), num()); e = (num(), num()); flatten([c, e], pos, cur); pos = e
        elif cmd == 'C':
            c1 = (num(), num()); c2 = (num(), num()); e = (num(), num()); flatten([c1, c2, e], pos, cur); pos = e
    if cur: subs.append(cur)
    return subs


def main():
    svg = open(SVG).read()
    g = re.search(r'<g transform="translate\(([-\d.]+) ([-\d.]+)\) scale\(([-\d.]+)\)"[^>]*stroke-width="([\d.]+)"', svg)
    tx, ty, sc, sw = (float(v) for v in g.groups())
    shapes, seen_palm = [], False
    for m in re.finditer(r'<path ([^>]*)/>', svg):
        a = dict(re.findall(r'([\w-]+)="([^"]*)"', m.group(1)))
        fill = a.get('fill', 'none')
        role = ROLES[fill.upper() if fill != 'none' else 'none']
        stroke = 0 if a.get('stroke') == 'none' else (2 if 'stroke' in a else 1)  # 0 none, 1 outline, 2 nail stroke
        if role == 'crease': stroke = 1
        swd = float(a.get('stroke-width', sw)) * sc
        if a.get('id') == 'palm-and-thumb': seen_palm = True
        # the paths between the cuff and the palm are the fingers: they curl out from behind the board's bottom edge
        behind = 1 if (role != 'cuff' and not seen_palm) else 0
        subs = [[(x * sc + tx, y * sc + ty) for x, y in s] for s in parse_d(a['d'])]
        shapes.append((a.get('id', role), role, stroke, swd, behind, subs))
    nail = [s for s in shapes if s[0] == 'thumbnail'][0][5][0]
    tip = (sum(p[0] for p in nail) / len(nail), sum(p[1] for p in nail) / len(nail))
    idx = [s for s in shapes if s[0] == 'index'][0][5][0]
    edge = min(p[1] for p in idx)  # the index finger's flat top is the board's bottom edge
    allp = [p for s in shapes for sub in s[5] for p in sub]
    L = ['// GENERATED by tools/svgHand.py from art/hand-left.svg. Do not edit; rerun the script.',
         '// Art: made by Lewis Moten with ChatGPT image generation (OpenAI); converted to firmware shapes by Claude Sonnet 5.5.',
         '// A left hand gripping a board: thumb over the front, fingers curled below its bottom edge, a cuff. Whole units of a',
         '// 1024 square, in draw order. stroke: 0 none, 1 outline, 2 nail stroke; behind: drawn only outside the board.',
         '#pragma once', '#include <stdint.h>', 'namespace hs {',
         'enum Role : uint8_t { CUFF, SKIN, SKIN_SHADE, NAIL, HIGHLIGHT, CREASE };',
         'struct Shape { Role role; uint8_t stroke, behind, subs; uint16_t first; float width; };  // width: stroke width in units',
         'struct Sub { uint16_t start, n; };']
    pts, subl, shl = [], [], []
    for (sid, role, stroke, swd, behind, subs) in shapes:
        first = len(subl)
        for s in subs:
            if s[0] == s[-1] and len(s) > 1: s = s[:-1]
            subl.append((len(pts), len(s)))
            pts += [(round(x), round(y)) for x, y in s]
        shl.append('  {%s, %d, %d, %d, %d, %.2ff},  // %s' % (NAMES[role], stroke, behind, len(subs), first, swd, sid))
    L.append('constexpr int SHAPES = %d, SUBS = %d, POINTS = %d;' % (len(shl), len(subl), len(pts)))
    # the curled fingers' outer (left) edge, stroke included: it sits flush with the board's outer edge
    fmin = min(p[0] for s in shapes if s[4] for sub in s[5] for p in sub) - 4.5
    L.append('constexpr float FINGER_MIN_X = %.1ff;  // the curled fingers\' outer edge, outline included' % fmin)
    L.append('constexpr float TIP_X =%.1ff, TIP_Y = %.1ff, EDGE_Y = %.1ff;  // thumbnail center; the board edge the fingers curl under' % (tip[0], tip[1], edge))
    L.append('constexpr float MIN_X = %.1ff, MAX_X = %.1ff, MIN_Y = %.1ff, MAX_Y = %.1ff;' % (min(p[0] for p in allp), max(p[0] for p in allp), min(p[1] for p in allp), max(p[1] for p in allp)))
    L.append('static const Shape shapes[SHAPES] = {'); L += shl; L.append('};')
    L.append('static const Sub subs[SUBS] = {' + ', '.join('{%d,%d}' % s for s in subl) + '};')
    L.append('static const int16_t pts[POINTS * 2] = {')
    for i in range(0, len(pts), 8): L.append('  ' + ', '.join('%d,%d' % p for p in pts[i:i + 8]) + ',')
    L.append('};'); L.append('}  // namespace hs')
    open(OUT, 'w').write('\n'.join(L) + '\n')
    print('%d shapes, %d points -> %s' % (len(shl), len(pts), os.path.relpath(OUT)))


main()
