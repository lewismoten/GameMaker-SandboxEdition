#!/usr/bin/env python3
# Traces the hand in the maintainer's reference photo (his own photo of the board held in his left hand, used with his
# permission) and writes the outline as a C header for src/firstrun.h. Reproducible: skin-colored pixels (HSV window) inside a
# hand-correction polygon -> the largest connected blob -> its outer contour -> approxPolyDP (Ramer-Douglas-Peucker) -> a few
# hand-fixes (listed below) -> points in units of 100 photo pixels with the thumb tip at (0, 0). The photo is never shipped; only
# these numbers are. The thumbnail and two knuckle creases are read off the photo by eye (constants below).
#   python3 tools/traceHand.py <photo.jpg> [--debug overlay.png] > src/handshape.h
# Needs: opencv-python, numpy.
import sys
import cv2
import numpy as np

photo = sys.argv[1]
dbg = sys.argv[sys.argv.index('--debug') + 1] if '--debug' in sys.argv else None
img = cv2.imread(photo)
h, w = img.shape[:2]
hsv = cv2.cvtColor(img, cv2.COLOR_BGR2HSV)
H, S, V = hsv[..., 0].astype(int), hsv[..., 1].astype(int), hsv[..., 2].astype(int)
mask = (((H <= 22) | (H >= 170)) & (S >= 50) & (S <= 200) & (V >= 90)).astype(np.uint8) * 255
# the hand-correction polygon: everything the hand can be (the wooden table, the cable and the board are outside it)
KEEP = np.array([(0, 128), (60, 136), (130, 130), (200, 126), (258, 134), (270, 165), (262, 192), (242, 206), (236, 240), (240, 270),
                 (240, 310), (226, 340), (180, 372), (110, 384), (0, 384)], np.int32)
keep = np.zeros_like(mask)
cv2.fillPoly(keep, [KEEP], 255)
mask = cv2.bitwise_and(mask, keep)
mask = cv2.morphologyEx(mask, cv2.MORPH_OPEN, np.ones((5, 5), np.uint8))
mask = cv2.morphologyEx(mask, cv2.MORPH_CLOSE, np.ones((9, 9), np.uint8))
n, lab, st, _ = cv2.connectedComponentsWithStats(mask)
best = max(range(1, n), key=lambda i: st[i, cv2.CC_STAT_AREA])
blob = (lab == best).astype(np.uint8) * 255
cs, _ = cv2.findContours(blob, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
c = max(cs, key=cv2.contourArea)
ap = cv2.approxPolyDP(c, 2.2, True)[:, 0, :]
pts = [tuple(int(v) for v in q) for q in ap]
print(f'traced {len(pts)} points from {photo} ({w}x{h}); blob area {int(cv2.contourArea(c))}', file=sys.stderr)
# Hand-fixes: the keep polygon leaves little steps along the thumb's top edge, and the photo cuts the hand at its left and bottom
# edges, so those are closed with a wrist running down and outward instead.
CUT = [(0, 136), (0, 383), (106, 383), (106, 375)]
trace = [q for q in pts if q not in CUT and not (125 <= q[1] <= 145 and 120 <= q[0] <= 240)]
j = trace.index((115, 374)) if (115, 374) in trace else 0
rest = trace[j:] + trace[:j]  # from the cut's lower end, round the finger lobes and the thumb tip
rest = [q for q in rest if q[1] >= 150 or q[0] >= 250]  # drop what is left of the top edge
ordered = [(237, 131), (180, 129), (130, 135), (71, 141), (41, 133), (-25, 230), (-45, 330), (-50, 430), (75, 430), (106, 383)] + rest
def chaikin(pl):  # one round of corner cutting: smooth the contour, keeping its shape
    out = []
    for i in range(len(pl)):
        a, b = pl[i], pl[(i + 1) % len(pl)]
        out += [(a[0] * 0.75 + b[0] * 0.25, a[1] * 0.75 + b[1] * 0.25), (a[0] * 0.25 + b[0] * 0.75, a[1] * 0.25 + b[1] * 0.75)]
    return out


ordered = chaikin(ordered)
TIP = (264, 166)
UNIT = 100.0
norm = lambda q: (round((q[0] - TIP[0]) / UNIT, 3), round((q[1] - TIP[1]) / UNIT, 3))
NAIL = (233, 157, 24, 23)  # center and radii, read off the photo's thumbnail
CREASE = [[(150, 255), (178, 262), (205, 275)], [(140, 330), (165, 338), (190, 345)]]  # the knuckle creases, read off the photo
if dbg:
    out = img.copy()
    cv2.polylines(out, [np.array(ordered, np.int32).reshape(-1, 1, 2)], True, (0, 255, 0), 1)
    cv2.ellipse(out, (NAIL[0], NAIL[1]), (NAIL[2], NAIL[3]), 0, 0, 360, (255, 0, 255), 1)
    for pl in CREASE:
        cv2.polylines(out, [np.array(pl, np.int32).reshape(-1, 1, 2)], False, (0, 255, 255), 1)
    cv2.imwrite(dbg, out)


def arr(name, pl):
    return f'constexpr float {name}[][2] = {{' + ', '.join(f'{{{norm(q)[0]}f, {norm(q)[1]}f}}' for q in pl) + '};'


print("// Generated by tools/traceHand.py from the maintainer's reference photo of the board held in his left hand; do not edit by hand.")
print('// Points are in units of 100 photo pixels, with (0, 0) at the thumb tip, x to the right (the thumb points right), y down.')
print('#pragma once')
print('namespace handshape {')
print(arr('OUTLINE', ordered))
print(f'constexpr int OUTLINE_N = {len(ordered)};')
print(f'constexpr float NAIL_X = {norm(NAIL[:2])[0]}f, NAIL_Y = {norm(NAIL[:2])[1]}f, NAIL_RX = {NAIL[2] / UNIT}f, NAIL_RY = {NAIL[3] / UNIT}f;')
for k, pl in enumerate(CREASE):
    print(arr(f'CREASE{k}', pl))
    print(f'constexpr int CREASE{k}_N = {len(pl)};')
print('}  // namespace handshape')
