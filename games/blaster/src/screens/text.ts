// and the readme on the disk (also 31 columns, for the same little windows).
import { withCreditPage } from '../../../kit/license';

const page = (lines: string[]) => {
  for (const l of lines) if (l.length > 31) throw new Error(`Text line over 31 columns: "${l}"`);
  if (lines.length > 16) throw new Error(`Page over 16 lines: "${lines[0]}"`);
  while (lines.length < 16) lines.push('');
  return lines.join('\n');
};
const pages = (...ps: string[][]) => ps.map(page).join('\n');

